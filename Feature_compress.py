    "def cross_validate_autoencoder(X, latent_dim=100, n_splits=3, epochs=300, batch_size=8, lr=1e-4, hidden_dims=None):\n",
    "    \"\"\"\n",
    "    Perform cross-validation for the autoencoder model\n",
    "    \n",
    "    Args:\n",
    "        X: Input data tensor\n",
    "        latent_dim: Dimensionality of the latent space\n",
    "        n_splits: Number of cross-validation folds\n",
    "        epochs: Maximum number of training epochs\n",
    "        batch_size: Batch size for training\n",
    "        lr: Learning rate\n",
    "        hidden_dims: List of hidden layer dimensions [h1, h2, h3]\n",
    "        \n",
    "    Returns:\n",
    "        r2_scores: List of R² scores for each fold\n",
    "        mse_scores: List of MSE scores for each fold\n",
    "    \"\"\"\n",
    "    input_dim = X.shape[1]\n",
    "    kf = KFold(n_splits=n_splits, shuffle=True, random_state=42)\n",
    "    r2_scores = []\n",
    "    mse_scores = []\n",
    "    fold = 1\n",
    "    \n",
    "    for train_idx, test_idx in kf.split(X):\n",
    "        print(f\"\\n===== Fold {fold} =====\")\n",
    "        X_train, X_test = X[train_idx], X[test_idx]\n",
    "        \n",
    "        model = ShortcutAutoencoder(input_dim=input_dim, latent_dim=latent_dim, hidden_dims=hidden_dims)\n",
    "        model, _ = train_autoencoder(model, X_train, epochs=epochs, batch_size=batch_size, lr=lr)\n",
    "        \n",
    "        # Get reconstructions on test set\n",
    "        model.eval()\n",
    "        with torch.no_grad():\n",
    "            X_recon, _ = model(X_test)\n",
    "            \n",
    "            # Calculate R² score\n",
    "            r2 = np.mean([\n",
    "                r2_score(X_test[:, i].numpy(), X_recon[:, i].numpy()) \n",
    "                for i in range(X.shape[1])\n",
    "            ])\n",
    "            r2_scores.append(r2)\n",
    "            \n",
    "            # Calculate Mean Squared Error\n",
    "            mse = nn.MSELoss()(X_test, X_recon).item()\n",
    "            mse_scores.append(mse)\n",
    "            \n",
    "            print(f\"Fold {fold} results:\")\n",
    "            print(f\"  R² Score: {r2:.4f}\")\n",
    "            print(f\"  MSE: {mse:.4f}\")\n",
    "        \n",
    "        fold += 1\n",
    "    \n",
    "    print(f\"\\n====== Cross-Validation Results ======\")\n",
    "    print(f\"Average R² over {n_splits} folds: {np.mean(r2_scores):.4f} ± {np.std(r2_scores):.4f}\")\n",
    "    print(f\"Average MSE over {n_splits} folds: {np.mean(mse_scores):.4f} ± {np.std(mse_scores):.4f}\")\n",
    "    return r2_scores, mse_scores\n",
