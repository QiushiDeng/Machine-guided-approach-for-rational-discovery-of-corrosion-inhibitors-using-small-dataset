    "class ShortcutAutoencoder(nn.Module):\n",
    "    def __init__(self, input_dim=209, latent_dim=2, hidden_dims=[512, 256, 128]):\n",
    "        super().__init__()\n",
    "        self.input_dim = input_dim\n",
    "        self.latent_dim = latent_dim\n",
    "        h1, h2, h3 = hidden_dims\n",
    "        # ENCODER\n",
    "        self.enc1 = nn.Sequential(\n",
    "            nn.Linear(input_dim, h1),\n",
    "            nn.BatchNorm1d(h1),\n",
    "            nn.ReLU()\n",
    "        )\n",
    "        self.enc2 = nn.Sequential(\n",
    "            nn.Linear(h1 + input_dim, h2),\n",
    "            nn.BatchNorm1d(h2),\n",
    "            nn.ReLU()\n",
    "        )\n",
    "        self.enc3 = nn.Sequential(\n",
    "            nn.Linear(h2 + input_dim, h3),\n",
    "            nn.BatchNorm1d(h3),\n",
    "            nn.ReLU()\n",
    "        )\n",
    "        self.enc_out = nn.Linear(h3 + input_dim, latent_dim)\n",
    "        \n",
    "        # DECODER\n",
    "        self.dec1 = nn.Sequential(\n",
    "            nn.Linear(latent_dim, h3),\n",
    "            nn.BatchNorm1d(h3),\n",
    "            nn.ReLU()\n",
    "        )\n",
    "        self.dec2 = nn.Sequential(\n",
    "            nn.Linear(h3 + latent_dim, h2),\n",
    "            nn.BatchNorm1d(h2),\n",
    "            nn.ReLU()\n",
    "        )\n",
    "        self.dec3 = nn.Sequential(\n",
    "            nn.Linear(h2 + latent_dim, h1),\n",
    "            nn.BatchNorm1d(h1),\n",
    "            nn.ReLU()\n",
    "        )\n",
    "        self.dec_out = nn.Sequential(\n",
    "            nn.Linear(h1 + latent_dim, input_dim),\n",
    "            nn.Tanh()  # Changed from Sigmoid to Tanh for normalized features\n",
    "        )\n",
    "    \n",
    "    def encode(self, x):\n",
    "        # Validate input dimensions\n",
    "        if x.shape[1] != self.input_dim:\n",
    "            raise ValueError(f\"Expected input dimension {self.input_dim}, got {x.shape[1]}\")\n",
    "            \n",
    "        x1 = self.enc1(x)\n",
    "        x2_input = torch.cat([x1, x], dim=1)\n",
    "        x2 = self.enc2(x2_input)\n",
    "        x3_input = torch.cat([x2, x], dim=1)\n",
    "        x3 = self.enc3(x3_input)\n",
    "        z_input = torch.cat([x3, x], dim=1)\n",
    "        z = self.enc_out(z_input)\n",
    "        return z\n",
    "    \n",
    "    def decode(self, z):\n",
    "        # Validate latent dimensions\n",
    "        if z.shape[1] != self.latent_dim:\n",
    "            raise ValueError(f\"Expected latent dimension {self.latent_dim}, got {z.shape[1]}\")\n",
    "            \n",
    "        d1 = self.dec1(z)\n",
    "        d2_input = torch.cat([d1, z], dim=1)\n",
    "        d2 = self.dec2(d2_input)\n",
    "        d3_input = torch.cat([d2, z], dim=1)\n",
    "        d3 = self.dec3(d3_input)\n",
    "        x_recon_input = torch.cat([d3, z], dim=1)\n",
    "        x_recon = self.dec_out(x_recon_input)\n",
    "        return x_recon\n",
    "    \n",
    "    def forward(self, x):\n",
    "        z = self.encode(x)\n",
    "        x_recon = self.decode(z)\n",
    "        return x_recon, z\n",
